const DECKS = { home: HOME, school: SCHOOL, route: ROUTE, shop: SHOP };

/** 場所の種類ごとのカードの束。「自由に作る」は全部の束(同じ名前は1枚)。 */
export function placeDeck(place) {
  if (DECKS[place]) return DECKS[place];
  const seen = new Set();
  const all = [];
  for (const card of [...HOME, ...SCHOOL, ...ROUTE, ...SHOP]) {
    if (seen.has(card.name)) continue;
    seen.add(card.name);
    all.push(card);
  }
  return Object.freeze(all);
}

