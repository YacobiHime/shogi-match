/** 5五に1枚だけ駒を置いた局面。玉は動きの範囲に入らない8一・2九へ置く。 */
function lonePieceSfen(symbol) {
  if (symbol === "K") return "1k7/9/9/9/4K4/9/9/9/9 b - 1";
  return `1k7/9/9/9/4${symbol}4/9/9/9/7K1 b - 1`;
}

