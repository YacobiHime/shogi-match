/**
 * 組み合わせると実在の棋士・女流棋士と同じになる名前。生成しないようにする(全員は網羅していない。見つけたら足す)。
 */
export const REAL_NAME_BLOCKLIST = Object.freeze(new Set([
  '小林健二', '中村修', '中川大輔', '西田拓也', '佐藤慎一', '遠藤正樹', '石井健太郎', '山崎隆之', '渡辺明', '渡部愛',
]));

const listFor = (eras, birthYear) => eras.find(({ until }) => birthYear <= until).names;

/**
 * 名前を作る。usedに入っている名前は使わない(使った名前はusedに足す)。
 * @param {{ next(): number }} rng
 * @param {Set<string>} used
 * @param {{ women?: boolean, age?: number }} options ageから生まれた年代を決める。
 */
export function newName(rng, used, { women = false, age = 30 } = {}) {
  const birthYear = BASE_YEAR - age;
  const eras = women ? WOMEN_NAMES_BY_ERA : GIVEN_NAMES_BY_ERA;
  for (let attempt = 0; attempt < 400; attempt += 1) {
    // 同じ名前が続いたら、隣の年代の名前も使う。
    const shift = attempt < 200 ? 0 : (attempt % 2 ? 10 : -10);
    const name = `${weightedPick(rng, SURNAME_WEIGHTS)}${pick(rng, listFor(eras, birthYear + shift))}`;
    if (!used.has(name) && !REAL_NAME_BLOCKLIST.has(name)) {
      used.add(name);
      return name;
    }
  }
  const name = `${weightedPick(rng, SURNAME_WEIGHTS)}${pick(rng, listFor(eras, birthYear))}${used.size}`;
  used.add(name);
  return name;
}
